// постоянное значение равное 10
const value1 = 10 

// рандомное целое число от 1 до10
const value2 = Math.floor(Math.random()*10)+1

// расчет по формуле
const result = value1 + value2/5 + 17

console.log(`Value2: ${value2}`)
console.log(`Result: ${result}`)

// КАК РАБОТАЕТ ПРИОРИТЕТ ОПЕРАТОРОВ В ЭТОМ СКПИПТЕ:

// Шаг 1: Производится деление value2 на 5, 
// Шаг 2: Производится сложение следующих слагаемых: 
//      1. value1, 
//      2. результат шага 1, 
//      3. 17.
// Шаг 3: Переменной Result присваивается результат Шага 2.



// ПРИОРИТЕТЫ ОПЕРАТОРОВ В JS:

// В JavaScript операторы выполняются в определённом порядке, 
// который называется приоритетом операторов. 
// Этот порядок определяет, какие операции выполняются раньше, 
// если в выражении нет скобок.

//  Примеры работы приоритетов операторов:

// 1. Умножение выполняется раньше сложения:

// let result = 10 + 2 * 5;
// console.log(result); 
// Итог: 20, потому что 2 * 5 = 10, а потом 10 + 10 = 20

// 2. Использование скобок изменяет приоритет

// let result = (10 + 2) * 5;
// console.log(result); 
// Итог: 60, потому что сначала 10 + 2 = 12, потом 12 * 5 = 60

// 3. Логические операторы выполняются позже арифметических

// let isGreater = 10 + 5 > 12 && 8 - 3 < 10;
// console.log(isGreater); 
// Итог: true, потому что сначала 10 + 5 > 12 (true), потом 8 - 3 < 10 (true), 
// и в итоге true && true = true

// 4. Оператор присваивания выполняется в последнюю очередь

// let x = 10;
// let y = 5;
// let result = x + y * 2;
// console.log(result); 
// Итог: 20, потому что сначала 5 * 2 = 10, потом 10 + 10 = 20

// ИТОГ:

// Если в выражении несколько операторов, 
// JavaScript сначала выполняет операторы с высоким приоритетом (умножение, деление), 
// а затем с низким (сложение, логические операции).

// Скобки () позволяют изменить порядок выполнения операций и сделать код понятнее.

